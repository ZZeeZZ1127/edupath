export function searchCatalog(query: string, limit = 12): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return INTEREST_CATALOG.slice(0, limit);
  return INTEREST_CATALOG.filter((name) => name.toLowerCase().includes(q)).slice(0, limit);
}
